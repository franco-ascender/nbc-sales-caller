import { test, expect } from '@playwright/test';
import type { Page } from '@playwright/test';
const artifacts = process.env.K01_ARTIFACT_DIR;
async function screenshot(page: Page, name: string): Promise<void> { if (artifacts) { await page.evaluate(() => { (document.activeElement as HTMLElement | null)?.blur(); window.scrollTo(0, 0); }); await page.screenshot({ path: `${artifacts}/${name}.png`, fullPage: true, animations: 'disabled' }); } }
async function downloadContents(page: Page, name: string): Promise<string> {
  const event = page.waitForEvent('download'); await page.getByRole('button', { name, exact: true }).click();
  const stream = await (await event).createReadStream(); if (!stream) throw new Error('Missing download');
  const chunks: Buffer[] = []; for await (const chunk of stream) chunks.push(Buffer.from(chunk)); return Buffer.concat(chunks).toString('utf8');
}
