test('create curriculum without JSON, then safely review a CSV replacement', async ({ page }) => {
  await page.goto('/academy'); await page.getByRole('button', { name: 'Import your program', exact: true }).click();
  await page.getByRole('button', { name: 'Add course', exact: true }).click();
  const form = page.getByRole('form', { name: 'Edit curriculum item' });
  await page.getByLabel('Course title').fill('K01 DEMO manual course'); await form.getByRole('button', { name: 'Add course', exact: true }).click();
  await page.getByRole('button', { name: 'Add module', exact: true }).click();
  await page.getByLabel('Module title').fill('K01 DEMO manual module'); await form.getByRole('button', { name: 'Add module', exact: true }).click();
  await page.getByRole('button', { name: 'Add lesson', exact: true }).click();
  await page.getByLabel('Lesson title').fill('K01 DEMO manual lesson'); await form.getByRole('button', { name: 'Add lesson', exact: true }).click();
  const before = JSON.parse(await downloadContents(page, 'Export inventory'));
  expect(before.courses[0].modules[0].lessons[0].title).toBe('K01 DEMO manual lesson');
  await page.getByLabel('Course inventory table').setInputFiles({name:'invalid.csv',mimeType:'text/csv',buffer:Buffer.from('Course,Module,Lesson\nMissing columns')});
  await expect(page.locator('main').getByRole('alert')).toContainText('Row 2');
  expect(JSON.parse(await downloadContents(page, 'Export inventory'))).toEqual(before);
  await page.getByLabel('Course inventory table').setInputFiles({name:'K01-DEMO-CSV.csv',mimeType:'text/csv',buffer:Buffer.from('Course,Module,Lesson\nK01 DEMO CSV course,Module,Lesson')});
  page.once('dialog', dialog => dialog.dismiss()); await page.getByRole('button', {name:'Use this curriculum',exact:true}).click();
  expect(JSON.parse(await downloadContents(page, 'Export inventory'))).toEqual(before);
  page.once('dialog', dialog => dialog.accept()); await page.getByRole('button', {name:'Use this curriculum',exact:true}).click();
  const after = JSON.parse(await downloadContents(page, 'Export inventory'));
  expect(after.courses[0].title).toBe('K01 DEMO CSV course'); expect(after.version).toBe(1);
});
